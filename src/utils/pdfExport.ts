import jsPDF from 'jspdf';
import 'jspdf-autotable';
import html2canvas from 'html2canvas';
import { format } from 'date-fns';
import { toast } from 'sonner';

export interface PDFExportOptions {
  title: string;
  subtitle?: string;
  hotelName?: string;
  hotelAddress?: string;
  hotelPhone?: string;
  hotelEmail?: string;
  dateRange?: { start: string; end: string };
  generatedBy?: string;
  currency?: string;
  filename: string;
  headers: string[];
  rows: (string | number)[][];
  summaryRows?: (string | number)[][];
  orientation?: 'portrait' | 'landscape';
  columnStyles?: Record<number, any>;
}

export interface GeneratePdfExportOptions {
  filename?: string;
  title?: string;
  pageSize?: 'a4' | 'letter';
  orientation?: 'portrait' | 'landscape';
  margin?: number; // mm
  scale?: number;
  backgroundColor?: string;
  autoSave?: boolean;
}

/**
 * Universal utility to export generated data tables as professional, formatted PDF documents.
 * Includes hotel branding header, metadata, elegant autoTable layout, totals, and running page footers.
 */
export function exportTableToPDF(options: PDFExportOptions): void {
  const {
    title,
    subtitle,
    hotelName = 'Hotel Property Management',
    hotelAddress,
    hotelPhone,
    hotelEmail,
    dateRange,
    generatedBy,
    currency,
    filename,
    headers,
    rows,
    summaryRows,
    orientation = headers.length > 6 ? 'landscape' : 'portrait',
    columnStyles
  } = options;

  const doc = new jsPDF({
    orientation,
    unit: 'mm',
    format: 'a4'
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  // Primary brand color: Emerald green #10b981
  const brandEmerald = [16, 185, 129] as [number, number, number];

  // Top header banner band (dark slate)
  doc.setFillColor(15, 23, 42);
  doc.rect(0, 0, pageWidth, 24, 'F');

  // Emerald brand accent line
  doc.setFillColor(16, 185, 129);
  doc.rect(0, 24, pageWidth, 1.5, 'F');

  // Hotel name & title in header
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text(hotelName, 14, 11);

  doc.setFontSize(8.5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(203, 213, 225);
  const contactParts = [hotelAddress, hotelPhone, hotelEmail].filter(Boolean);
  if (contactParts.length > 0) {
    doc.text(contactParts.join('  |  '), 14, 17);
  } else {
    doc.text('Hotel Property Management System  |  Automated Operational & Financial Record', 14, 17);
  }

  // Right side of top banner: report generation date & currency
  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184);
  doc.text(`Generated: ${format(new Date(), 'yyyy-MM-dd HH:mm')}`, pageWidth - 14, 11, { align: 'right' });
  if (currency) {
    doc.text(`Currency: ${currency}`, pageWidth - 14, 17, { align: 'right' });
  }

  // Report Title & Metadata section below banner
  let currentY = 32;
  doc.setTextColor(15, 23, 42);
  doc.setFontSize(15);
  doc.setFont('helvetica', 'bold');
  doc.text(title, 14, currentY);

  currentY += 6;
  doc.setFontSize(8.5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(71, 85, 105);

  const metaItems: string[] = [];
  if (dateRange?.start && dateRange?.end) {
    metaItems.push(`Period: ${dateRange.start} to ${dateRange.end}`);
  }
  if (subtitle) {
    metaItems.push(subtitle);
  }
  if (generatedBy) {
    metaItems.push(`Generated by: ${generatedBy}`);
  }
  metaItems.push(`Total Records: ${rows.length}`);

  doc.text(metaItems.join('   •   '), 14, currentY);
  currentY += 4;

  // AutoTable configuration
  (doc as any).autoTable({
    startY: currentY,
    head: [headers],
    body: rows,
    foot: summaryRows && summaryRows.length > 0 ? summaryRows : undefined,
    theme: 'grid',
    headStyles: {
      fillColor: brandEmerald,
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 8,
      cellPadding: 2.2
    },
    footStyles: {
      fillColor: [241, 245, 249],
      textColor: [15, 23, 42],
      fontStyle: 'bold',
      fontSize: 8,
      cellPadding: 2.5
    },
    styles: {
      font: 'helvetica',
      fontSize: 7.5,
      cellPadding: 1.8,
      textColor: [30, 41, 59],
      lineColor: [226, 232, 240],
      lineWidth: 0.1,
      overflow: 'linebreak'
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252]
    },
    columnStyles: columnStyles || {}
  });

  // Stamp running headers/footers on all generated pages after autoTable calculates total page count
  const totalPages = (doc as any).internal.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFontSize(7.5);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(148, 163, 184);

    // Top of footer border
    doc.setDrawColor(226, 232, 240);
    doc.setLineWidth(0.2);
    doc.line(14, pageHeight - 9, pageWidth - 14, pageHeight - 9);

    doc.text(`${hotelName}  •  Confidential & Proprietary Document`, 14, pageHeight - 5);
    doc.text(`Page ${i} of ${totalPages}`, pageWidth - 14, pageHeight - 5, { align: 'right' });
  }

  const cleanFilename = filename.endsWith('.pdf') ? filename : `${filename}.pdf`;
  doc.save(cleanFilename);
}

/**
 * Universal PDF Export Utility that utilizes the existing standardized print layout
 * (e.g., PrintTemplate, active-hotel-receipt, receipt-container, or custom printable element)
 * to generate downloadable, multi-page, high-resolution PDF files for guests.
 * 
 * Automatically strips all extraneous UI elements, close buttons, action toolbars,
 * and toast overlays, producing a clean, paper-optimized vector-sharp document.
 */
export async function generatePdfExport(
  target?: HTMLElement | string | null | GeneratePdfExportOptions,
  options?: GeneratePdfExportOptions
): Promise<jsPDF | void> {
  let resolvedElement: HTMLElement | null = null;
  let resolvedOptions: GeneratePdfExportOptions = {};

  // Check if target is actually options object
  if (target && typeof target === 'object' && !(target instanceof HTMLElement)) {
    resolvedOptions = target as GeneratePdfExportOptions;
  } else {
    if (typeof target === 'string') {
      resolvedElement = document.getElementById(target) || document.querySelector<HTMLElement>(target);
    } else if (target instanceof HTMLElement) {
      resolvedElement = target;
    }
    if (options) {
      resolvedOptions = options;
    }
  }

  // Fallback discovery: Look for active standardized printable containers in priority order
  if (!resolvedElement && typeof document !== 'undefined') {
    const prioritySelectors = [
      '#standard-print-document',
      '#active-hotel-receipt',
      '.receipt-container',
      '#bulk-settle-invoice',
      '#superadmin-subscription-receipt',
      '#staff-handover-slip',
      '#fandb-kitchen-docket',
      '#breakfast-manifest-print-container',
      '#dss-guest-report-print-container',
      '#reports-analytics-print-container',
      '.print-container',
      '[data-printable="true"]'
    ];

    for (const sel of prioritySelectors) {
      const found = document.querySelector<HTMLElement>(sel);
      if (found && (found.offsetWidth > 0 || found.offsetHeight > 0 || found.isConnected)) {
        resolvedElement = found;
        break;
      }
    }
  }

  if (!resolvedElement) {
    console.error('generatePdfExport: No printable element or layout template found in the DOM.');
    toast.error('Could not locate printable document layout.');
    return;
  }

  const {
    filename,
    title = 'Document',
    pageSize = 'a4',
    orientation = 'portrait',
    margin = 8,
    scale = 2,
    backgroundColor = '#ffffff',
    autoSave = true
  } = resolvedOptions;

  const toastId = toast.loading('Generating high-resolution PDF...');

  try {
    // Capture high-fidelity canvas representation
    const canvas = await html2canvas(resolvedElement, {
      scale,
      useCORS: true,
      allowTaint: true,
      backgroundColor,
      logging: false,
      ignoreElements: (element: Element) => {
        const classNames = element.className || '';
        const isStringClass = typeof classNames === 'string';
        if (
          isStringClass && (
            classNames.includes('print:hidden') ||
            classNames.includes('no-print') ||
            classNames.includes('print-hidden')
          )
        ) {
          return true;
        }
        if (element.hasAttribute('data-sonner-toaster')) {
          return true;
        }
        if (element.tagName === 'BUTTON' && !element.classList?.contains('allow-print')) {
          return true;
        }
        return false;
      }
    });

    const pdf = new jsPDF({
      orientation,
      unit: 'mm',
      format: pageSize
    });

    const pageWidth = pdf.internal.pageSize.getWidth();
    const pageHeight = pdf.internal.pageSize.getHeight();
    const marginMm = margin;
    const contentWidthMm = pageWidth - marginMm * 2;
    const contentHeightMm = pageHeight - marginMm * 2;

    const canvasWidth = canvas.width;
    const canvasHeight = canvas.height;
    const pxPerMm = canvasWidth / contentWidthMm;
    const pageHeightPx = contentHeightMm * pxPerMm;

    let renderedHeightPx = 0;
    let pageNum = 0;

    // Slice canvas page by page for clean multi-page documents
    while (renderedHeightPx < canvasHeight) {
      if (pageNum > 0) {
        pdf.addPage(pageSize, orientation);
      }

      const sliceHeightPx = Math.min(pageHeightPx, canvasHeight - renderedHeightPx);
      const pageCanvas = document.createElement('canvas');
      pageCanvas.width = canvasWidth;
      pageCanvas.height = sliceHeightPx;
      const ctx = pageCanvas.getContext('2d');

      if (ctx) {
        ctx.fillStyle = backgroundColor;
        ctx.fillRect(0, 0, canvasWidth, sliceHeightPx);
        ctx.drawImage(
          canvas,
          0, renderedHeightPx, canvasWidth, sliceHeightPx,
          0, 0, canvasWidth, sliceHeightPx
        );

        const sliceDataUrl = pageCanvas.toDataURL('image/jpeg', 0.95);
        const sliceHeightMm = sliceHeightPx / pxPerMm;
        pdf.addImage(sliceDataUrl, 'JPEG', marginMm, marginMm, contentWidthMm, sliceHeightMm);
      }

      renderedHeightPx += sliceHeightPx;
      pageNum++;
    }

    // Add clean running footers
    const totalPages = (pdf as any).internal.getNumberOfPages();
    for (let i = 1; i <= totalPages; i++) {
      pdf.setPage(i);
      pdf.setFontSize(7.5);
      pdf.setFont('helvetica', 'normal');
      pdf.setTextColor(148, 163, 184);

      pdf.text(
        `Official Guest Document  •  Generated on ${format(new Date(), 'yyyy-MM-dd HH:mm')}`,
        marginMm,
        pageHeight - 4
      );
      pdf.text(
        `Page ${i} of ${totalPages}`,
        pageWidth - marginMm,
        pageHeight - 4,
        { align: 'right' }
      );
    }

    const defaultFilename = `${title.toLowerCase().replace(/[^a-z0-9]/g, '-')}-${format(new Date(), 'yyyyMMdd-HHmm')}.pdf`;
    const finalFilename = filename 
      ? (filename.endsWith('.pdf') ? filename : `${filename}.pdf`)
      : defaultFilename;

    if (autoSave) {
      pdf.save(finalFilename);
    }

    toast.dismiss(toastId);
    toast.success('PDF document downloaded successfully');
    return pdf;
  } catch (err: any) {
    console.error('generatePdfExport error:', err);
    toast.dismiss(toastId);
    toast.error('Failed to generate PDF. Please try again.');
  }
}

